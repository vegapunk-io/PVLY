"""Central configuration (12-factor: everything overridable via environment variables)."""
import os
import pathlib

BASE_DIR = pathlib.Path(__file__).resolve().parent.parent
DATA_DIR = pathlib.Path(os.getenv("PROVENABLY_DATA_DIR", BASE_DIR / "data"))
BLOB_DIR = DATA_DIR / "blobs"
DB_PATH = DATA_DIR / "provenably.sqlite3"
DEMO_DIR = BASE_DIR / "demo_assets"
CERT_DIR = DATA_DIR / "certs"
TRUST_DIR = DATA_DIR / "trust"

APP_NAME = "Provenably"
APP_VERSION = "0.1.0-prototype"

# Retention: uploaded bytes are deleted after this many hours (reports stay).
BLOB_TTL_HOURS = float(os.getenv("BLOB_TTL_HOURS", "24"))
# Hash-only mode: never keep the uploaded bytes after analysis.
HASH_ONLY_DEFAULT = os.getenv("HASH_ONLY", "false").lower() == "true"
MAX_UPLOAD_MB = int(os.getenv("MAX_UPLOAD_MB", "200"))
REQUIRE_AUTH = os.getenv("PROVENABLY_REQUIRE_AUTH", "").lower() in ("1", "true", "yes")
RATE_LIMIT_PER_MINUTE = int(os.getenv("RATE_LIMIT_PER_MINUTE", "120"))
TRUST_PROXY_HEADERS = os.getenv("TRUST_PROXY_HEADERS", "").lower() in ("1", "true", "yes")

# API keys. Empty list = open prototype (local use). Comma separated list enables enforcement.
API_KEYS = [k.strip() for k in os.getenv("PROVENABLY_API_KEYS", "").split(",") if k.strip()]

# C2PA trust configuration.
# - Official anchors: run `python tools/fetch_trust_list.py` (writes data/trust/anchors.pem)
# - Demo anchor: the test Root CA generated by tools/dev_cert.py (so demo files show "Trusted")
TRUST_ANCHORS_PEM = pathlib.Path(os.getenv("TRUST_ANCHORS_PEM", TRUST_DIR / "anchors.pem"))
TRUST_ALLOWED_PEM = pathlib.Path(os.getenv("TRUST_ALLOWED_PEM", TRUST_DIR / "allowed.pem"))
INCLUDE_DEMO_TRUST_ANCHOR = os.getenv("INCLUDE_DEMO_TRUST_ANCHOR", "true").lower() == "true"
DEMO_ROOT_CA_PEM = CERT_DIR / "demo_root_ca.pem"
DEMO_CHAIN_PEM = CERT_DIR / "demo_chain.pem"
DEMO_SIGNER_KEY_PEM = CERT_DIR / "demo_signer_key.pem"

# Vendor verifier connectors (MANUAL INTEGRATION — see README "Manual integration checklist").
OPENAI_VERIFY_API_KEY = os.getenv("OPENAI_VERIFY_API_KEY", "")
OPENAI_VERIFY_ENDPOINT = os.getenv("OPENAI_VERIFY_ENDPOINT", "")
GOOGLE_SYNTHID_ENDPOINT = os.getenv("GOOGLE_SYNTHID_ENDPOINT", "")
GOOGLE_ACCESS_TOKEN = os.getenv("GOOGLE_ACCESS_TOKEN", "")

# URL ingestion limits
URL_FETCH_TIMEOUT = float(os.getenv("URL_FETCH_TIMEOUT", "15"))

for _d in (DATA_DIR, BLOB_DIR, TRUST_DIR, CERT_DIR):
    _d.mkdir(parents=True, exist_ok=True)
